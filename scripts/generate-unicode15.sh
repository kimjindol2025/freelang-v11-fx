#!/usr/bin/env bash
# Read installed Unicode data as text. Never run Perl or a code generator in JS/Python.
set -Eeuo pipefail
data_root="${UNICODE_DATA_ROOT:-/usr/share/perl5/unicore}"
for file in To/Lc.pl To/Uc.pl SpecialCasing.txt lib/Cased/Y.pl lib/CI/Y.pl; do
  test -r "$data_root/$file"
  head -n 5 "$data_root/$file" | rg -q '15\.0\.0'
done
{
  echo '/* Unicode 15.0.0 data. Copyright Unicode, Inc.; see Unicode-LICENSE.'
  echo ' * Generated by scripts/generate-unicode15.sh from Unicode data tables.'
  echo ' * Input tables are read as text; no Perl interpreter is used. */'
  echo 'typedef struct { uint32_t first,last,to; } UMap;'
  for mode in Lc Uc; do
    printf 'static const UMap unicode_%s[] = {\n' "$mode"
    awk -F '\t' '/^return /{active=1;next} /^END/{active=0} active&&$1~/^[0-9A-F]+$/ {a=strtonum("0x"$1);b=$2==""?a:strtonum("0x"$2);c=strtonum("0x"$3);printf "{0x%X,0x%X,0x%X},\n",a,b,c}' "$data_root/To/$mode.pl"
    echo '};'
  done
  echo 'typedef struct {uint32_t cp,lo[3],up[3];unsigned ln,un;} USpecial;'
  echo 'static const USpecial unicode_special[] = {'
  awk -F ';' 'function trim(s){gsub(/^[ \t]+|[ \t]+$/,"",s);return s} /^[0-9A-F]/ {cond=$5;sub(/#.*/,"",cond);if(trim(cond)!="")next;ln=split(trim($2),lo,/ +/);un=split(trim($4),up,/ +/);printf "{0x%s,{",trim($1);for(i=1;i<=3;i++)printf "%s0x%s",(i>1?",":""),(i<=ln?lo[i]:"0");printf "},{";for(i=1;i<=3;i++)printf "%s0x%s",(i>1?",":""),(i<=un?up[i]:"0");printf "},%d,%d},\n",ln,un}' "$data_root/SpecialCasing.txt"
  echo '};'
  for mode in Cased CI; do
    printf 'static const uint32_t unicode_%s[] = {\n' "$mode"
    awk '/^return /{active=1;next}/^END/{active=0}active&&/^[0-9]+$/{printf "%s,",$0;if(++n%10==0)printf "\n"}END{print ""}' "$data_root/lib/$mode/Y.pl"
    echo '};'
  done
} > runtime/unicode15.h
