#!/usr/bin/env bash
# Exact native names must win before a user function's hyphen/underscore alias.
set -Eeuo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
output=$(mktemp)
staged=""
trap 'rm -f "$output"; [[ -z "$staged" ]] || rm -f "$staged"' EXIT
{
    echo '/* Generated by scripts/refresh-native-symbols.sh --write. */'
    echo 'static const char *const fl_native_names[] = {'
    {
        awk '{line=$0;while(match(line,/(^|;)[[:space:]]*FLValue[[:space:]]+([A-Za-z_][A-Za-z0-9_]*)[[:space:]]*\(/,a)){print a[2];name=a[2];gsub(/_/,"-",name);print name;line=substr(line,RSTART+RLENGTH)}}' "$ROOT/runtime/runtime.h"
        awk '{line=$0;while(match(line,/\(= \$op "([^"]+)"/,a)){print a[1];line=substr(line,RSTART+RLENGTH)}}' "$ROOT/self/cgc-main.fl"
        awk '{line=$0;while(match(line,/"([^"]+)"/,a)){print a[1];line=substr(line,RSTART+RLENGTH)}}' "$ROOT/runtime/v11-ops.h"
    } | LC_ALL=C sort -u | awk '{if(n%4==0)printf "    ";else printf " ";printf "\"%s\",",$0;if(++n%4==0)printf "\n"}END{if(n%4)printf "\n"}'
    echo '    NULL'
    echo '};'
} > "$output"
if [[ "${1:---check}" == --write ]]; then
    staged=$(mktemp "$ROOT/runtime/.native-symbols.XXXXXX")
    cp "$output" "$staged"
    mv "$staged" "$ROOT/runtime/native-symbols.h"
else
    diff -u "$ROOT/runtime/native-symbols.h" "$output"
    echo NATIVE_SYMBOL_METADATA=PASS
fi
